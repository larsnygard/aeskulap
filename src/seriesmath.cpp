// Read a frame's stored pixels as int32 with modality LUT (slope/intercept)
// applied, like the viewer's LUT input domain.
bool SeriesMath::load_pixels(const Glib::RefPtr<ImagePool::Instance>& inst,
                             std::vector<gint32>& out, int& w, int& h, bool& is_signed)
{
    out.clear();
    w = h = 0;
    if(!inst || inst->iscolor() || inst->bpp() != 16) {
        return false;
    }
    const void* p = inst->pixels(0);
    if(!p) {
        return false;
    }
    w = inst->width();
    h = inst->height();
    is_signed = inst->is_signed();
    size_t n = (size_t)w * h;
    out.resize(n);
    double slope = inst->slope();
    double intercept = inst->intercept();
    if(is_signed) {
        const gint16* s = (const gint16*)p;
        for(size_t i = 0; i < n; i++) {
            out[i] = (gint32)(s[i] * slope + intercept);
        }
    }
    else {
        const guint16* u = (const guint16*)p;
        for(size_t i = 0; i < n; i++) {
            out[i] = (gint32)(u[i] * slope + intercept);
        }
    }
    return true;
}

bool SeriesMath::write_frame(const std::vector<gint16>& frame, int w, int h,
                             const std::string& path,
                             const std::string& studyuid,
                             const std::string& seriesuid,
                             const std::string& description,
                             int frame_index, int total_frames)
{
    DcmFileFormat ff;
    DcmDataset* dset = ff.getDataset();

    // The meta-header (group 0002) is generated by saveFile(EWM_createNewMeta);
    // the dataset itself must not contain group 0002 elements.
    char uid[64];
    dcmGenerateUniqueIdentifier(uid, SITE_INSTANCE_UID_ROOT);

    dset->putAndInsertString(DCM_SOPClassUID, UID_SecondaryCaptureImageStorage);
    dset->putAndInsertString(DCM_SOPInstanceUID, uid);
    dset->putAndInsertString(DCM_StudyInstanceUID, studyuid.c_str());
    dset->putAndInsertString(DCM_SeriesInstanceUID, seriesuid.c_str());
    dset->putAndInsertString(DCM_Modality, "SC");
    dset->putAndInsertString(DCM_SeriesDescription, description.c_str());
    dset->putAndInsertString(DCM_Manufacturer, "Aeskulap");
    dset->putAndInsertString(DCM_ConversionType, "WSD");

    char dt[16], tm[16];
    {
        time_t t = time(NULL);
        struct tm* lt = localtime(&t);
        sprintf(dt, "%04d%02d%02d", lt->tm_year+1900, lt->tm_mon+1, lt->tm_mday);
        sprintf(tm, "%02d%02d%02d.000", lt->tm_hour, lt->tm_min, lt->tm_sec);
    }
    dset->putAndInsertString(DCM_StudyDate, dt);
    dset->putAndInsertString(DCM_SeriesDate, dt);
    dset->putAndInsertString(DCM_ContentDate, dt);
    dset->putAndInsertString(DCM_StudyTime, tm);
    dset->putAndInsertString(DCM_SeriesTime, tm);

    dset->putAndInsertUint16(DcmTagKey(0x0020,0x0012), (Uint16)total_frames);  // NumberOfInstancesInSeries
    dset->putAndInsertUint16(DCM_SeriesNumber, 9999);
    dset->putAndInsertUint16(DCM_InstanceNumber, (Uint16)(frame_index + 1));

    dset->putAndInsertUint16(DCM_SamplesPerPixel, 1);
    dset->putAndInsertString(DCM_PhotometricInterpretation, "MONOCHROME2");
    dset->putAndInsertUint16(DCM_PixelRepresentation, 1);  // signed
    dset->putAndInsertUint16(DCM_Rows, (Uint16)h);
    dset->putAndInsertUint16(DCM_Columns, (Uint16)w);
    dset->putAndInsertUint16(DCM_BitsAllocated, 16);
    dset->putAndInsertUint16(DCM_BitsStored, 16);
    dset->putAndInsertUint16(DCM_HighBit, 15);
    dset->putAndInsertUint16(DCM_PixelPaddingValue, 0);

    // min/max of this frame for a sane default W/L
    gint16 mn = 32767, mx = -32768;
    for(size_t i = 0; i < frame.size(); i++) {
        if(frame[i] < mn) mn = frame[i];
        if(frame[i] > mx) mx = frame[i];
    }
    dset->putAndInsertSint16(DCM_SmallestImagePixelValue, mn);
    dset->putAndInsertSint16(DCM_LargestImagePixelValue, mx);
    dset->putAndInsertSint16(DCM_RescaleIntercept, 0);
    dset->putAndInsertSint16(DCM_RescaleSlope, 1);

    Uint32 len = (Uint32)(frame.size() * 2);
    dset->putAndInsertUint16Array(DCM_PixelData, (const Uint16*)&frame[0], len);

    dset->putAndInsertString(DCM_SpecificCharacterSet, "ISO_IR 192");

    OFCondition rc = ff.saveFile(path.c_str(),
                                 EXS_LittleEndianExplicit,
                                 EET_ExplicitLength,
                                 EGL_recalcGL,
                                 EPD_withPadding,
                                 0, 0,
                                 EWM_createNewMeta);
    return rc.good();
}

static void sanitize(const std::string& uid, std::string& out) {
    out.clear();
    for(size_t i = 0; i < uid.size() && out.size() < 60; i++) {
        char c = uid[i];
        if((c >= '0' && c <= '9') || c == '.') out += c;
    }
}

SeriesMath::Result SeriesMath::subtract(
        const std::vector<Glib::RefPtr<ImagePool::Instance> >& a,
        const std::vector<Glib::RefPtr<ImagePool::Instance> >& b,
        const std::string& outdir,
        const std::string& studyuid,
        const std::string& seriesuid,
        const std::string& description)
{
    Result res = {0, 0, 0, true};
    size_t n = std::min(a.size(), b.size());
    if(n == 0) {
        return res;
    }

    std::string suid, sseries;
    sanitize(studyuid, suid);
    sanitize(seriesuid, sseries);
    if(suid.empty() || sseries.empty()) {
        return res;
    }
    mkdir(outdir.c_str(), 0755);

    for(size_t i = 0; i < n; i++) {
        std::vector<gint32> pa, pb;
        int wa, ha, wb, hb;
        bool sa, sb;
        if(!load_pixels(a[i], pa, wa, ha, sa) || !load_pixels(b[i], pb, wb, hb, sb)) {
            continue;
        }
        if(wa != wb || ha != hb) {
            continue;
        }
        if(res.frames == 0) {
            res.width = wa;
            res.height = ha;
        }
        std::vector<gint16> frame(pa.size());
        for(size_t k = 0; k < pa.size(); k++) {
            long v = (long)pa[k] - (long)pb[k];
            if(v > 32767) v = 32767;
            if(v < -32768) v = -32768;
            frame[k] = (gint16)v;
        }
        char name[256];
        snprintf(name, sizeof(name), "%s/sub%04zu.dcm", outdir.c_str(), i + 1);
        if(write_frame(frame, wa, ha, name, suid, sseries, description,
                       (int)i, (int)n)) {
            res.frames++;
        }
    }
    return res;
}

SeriesMath::Result SeriesMath::maximum_intensity_project(
        const std::vector<Glib::RefPtr<ImagePool::Instance> >& a,
        const std::string& outdir,
        const std::string& studyuid,
        const std::string& seriesuid,
        const std::string& description)
{
    Result res = {0, 0, 0, true};
    if(a.empty()) {
        return res;
    }
    std::string suid, sseries;
    sanitize(studyuid, suid);
    sanitize(seriesuid, sseries);
    if(suid.empty() || sseries.empty()) {
        return res;
    }
    mkdir(outdir.c_str(), 0755);

    // first frame defines the grid
    std::vector<gint32> first;
    int w = 0, h = 0;
    bool sgn = false;
    size_t start = 0;
    for(size_t i = 0; i < a.size(); i++) {
        if(load_pixels(a[i], first, w, h, sgn)) { start = i; break; }
    }
    if(w == 0) {
        return res;
    }
    std::vector<gint32> acc = first;
    for(size_t i = start + 1; i < a.size(); i++) {
        std::vector<gint32> p;
        int w2, h2;
        bool s2;
        if(!load_pixels(a[i], p, w2, h2, s2) || w2 != w || h2 != h) {
            continue;
        }
        for(size_t k = 0; k < acc.size(); k++) {
            if(p[k] > acc[k]) acc[k] = p[k];
        }
    }
    std::vector<gint16> frame(acc.size());
    for(size_t k = 0; k < acc.size(); k++) {
        long v = acc[k];
        if(v > 32767) v = 32767;
        if(v < -32768) v = -32768;
        frame[k] = (gint16)v;
    }
    char name[256];
    snprintf(name, sizeof(name), "%s/mip0001.dcm", outdir.c_str());
    if(write_frame(frame, w, h, name, suid, sseries, description, 0, 1)) {
        res.frames = 1;
        res.width = w;
        res.height = h;
    }
    return res;
}

